// This packer handles this project's named ES imports/exports and xmldom's
// relative CommonJS imports. Unknown syntax/dependencies fail the build.
async function addModule(file){
  file=path.resolve(file);
  const id=moduleId(file);
  if(modules.has(id))return id;
  modules.set(id,'');
  if(file===path.join(web,'engine','pdf-engine.js')){
    modules.set(id,'exports.PdfEngine=class { constructor() {} async extract(){throw new Error("此技能包支持 DOCX/XLSX/PPTX，PDF 请使用原项目的 PDF 页面。");} async compare(){return this.extract();} async annotate(){return this.extract();} };');
    return id;
  }
  const original=await readFile(file,'utf8');
  sources.push({path:id,sha256:digest(original)});
  let code=original;
  if(file.startsWith(path.dirname(xmlEntry)+path.sep)){
    const imports=[...code.matchAll(/\brequire\(['"]([^'"]+)['"]\)/g)];
    for(const match of imports){
      if(!match[1].startsWith('.'))throw new Error('Unexpected CommonJS dependency: '+match[1]);
      const dependency=await addModule(path.resolve(path.dirname(file),match[1]+'.js'));
      code=code.replaceAll(match[0],`require(${JSON.stringify(dependency)})`);
    }
  }else{
    const imports=[...code.matchAll(/\bimport\s*\{([^}]+)\}\s*from\s*['"]([^'"]+)['"];?/g)];
    for(const match of imports){
      if(!match[2].startsWith('.'))throw new Error('Unexpected ES dependency: '+match[2]);
      const dependency=await addModule(path.resolve(path.dirname(file),match[2]));
      const names=match[1].split(',').map(part=>part.trim().replace(/\s+as\s+/,':')).join(',');
      code=code.replace(match[0],`const {${names}}=require(${JSON.stringify(dependency)});`);
    }
    const exports=new Map();
    code=code.replace(/\bexport\s+(async\s+)?(function|class|const|let|var)\s+([A-Za-z_$][\w$]*)/g,(_,async,kind,name)=>{
      exports.set(name,name);return (async??'')+kind+' '+name;
    });
    code=code.replace(/\bexport\s*\{([^}]+)\};?/g,(_,list)=>{
      for(const part of list.split(',')){
        const [local,alias]=part.trim().split(/\s+as\s+/);
        if(local)exports.set(alias??local,local);
      }
      return '';
    });
    code=code.replaceAll('import.meta.url',JSON.stringify('https://office-diff.invalid/'+id));
    if(/^\s*(?:import|export)\b/m.test(code))throw new Error('Unhandled module syntax: '+id);
    code+='\nObject.assign(exports,{'+[...exports].map(([name,local])=>`${JSON.stringify(name)}:${local}`).join(',')+'});';
  }
  modules.set(id,code);
  return id;
}

